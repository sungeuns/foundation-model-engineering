// Reproduce the chapter 4.2 figures with: node scripts/generate-decoder-mask.mjs
import { writeFileSync } from 'node:fs';

const labels = {
  en: {
    title: 'Causal self-attention mask for four tokens',
    description: 'Rows are query positions and columns are key positions. Row 1 can use key 1, row 2 keys 1–2, row 3 keys 1–3, and row 4 keys 1–4. Check marks show which keys may contribute. Their attention weights depend on the query and key vectors.',
    query: 'Query i', key: 'Key position j', allowed: 'Allowed', blocked: 'Blocked',
  },
  ko: {
    title: '토큰 네 개의 인과적 자기 어텐션 마스크',
    description: '행은 질의 위치, 열은 키 위치입니다. 1번 행은 1번 키, 2번 행은 1~2번 키, 3번 행은 1~3번 키, 4번 행은 1~4번 키를 참조할 수 있습니다. 체크 표시는 참조가 허용된 위치를 뜻합니다. 각 위치의 어텐션 가중치는 질의와 키 벡터에 따라 달라집니다.',
    query: '질의 위치 i', key: '키 위치 j', allowed: '참조 허용', blocked: '참조 차단',
  },
};

const positions = [1, 2, 3, 4];
const columnCenter = j => 115 + 57 * (j - 1);
const rowCenter = i => 80 + 36 * (i - 1);

// Both the legend and the matrix use the same pair of marks, even in grayscale.
function mark(x, y, width, height, allowed) {
  const box = `<rect x="${-width / 2}" y="${-height / 2}" width="${width}" height="${height}" rx="3" fill="${allowed ? '#24645b' : '#eef2f1'}"/>`;
  const symbol = allowed
    ? '<path d="m-5 0 3.4 3.4 6.5-7" stroke="white"/>'
    : '<path d="m-4-4 8 8m-8 0 8-8" stroke="#556361"/>';
  return `<g transform="translate(${x} ${y})">${box}${symbol}</g>`;
}

function figure(lang, t) {
  const columnLabels = positions.map(j => `  <text x="${columnCenter(j)}" y="52">${j}</text>`).join('\n');
  const rowLabels = positions.map(i => `  <text x="49" y="${rowCenter(i) + 6}">${i}</text>`).join('\n');
  const cells = positions.flatMap(i => positions.map(j =>
    `  <g data-query="${i}" data-key="${j}">${mark(columnCenter(j), rowCenter(i), 53, 32, j <= i)}</g>`
  )).join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="250" viewBox="0 0 360 250" xml:lang="${lang}" role="img" aria-labelledby="mask-title mask-desc">
<!-- Generated by scripts/generate-decoder-mask.mjs using j ≤ i. -->
<title id="mask-title">${t.title}</title>
<desc id="mask-desc">${t.description}</desc>
<rect width="360" height="250" fill="white"/>
<g font-family="system-ui, Noto Sans CJK KR, sans-serif" fill="#1e3533">
 <g text-anchor="middle" font-size="15" font-weight="600">
  <text x="200.5" y="23">${t.key}</text>
  <text x="49" y="52">${t.query}</text>
 </g>
 <g text-anchor="middle" font-size="17" font-weight="600">
${columnLabels}
${rowLabels}
 </g>
 <g fill="none" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
${cells}
  ${mark(93, 229, 23, 21, true)}
  ${mark(206, 229, 23, 21, false)}
 </g>
 <g font-size="15">
  <text x="111" y="234">${t.allowed}</text>
  <text x="224" y="234">${t.blocked}</text>
 </g>
</g>
</svg>
`;
}

for (const [lang, copy] of Object.entries(labels)) {
  const asset = new URL(`../src/assets/images/chapter-4/decoder_only_causal_mask_${lang}.svg`, import.meta.url);
  writeFileSync(asset, figure(lang, copy));
}
